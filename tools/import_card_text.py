#!/usr/bin/env python3
"""Join the upstream card databases into review inputs for data/cards.toml.

Reads (written by tools/fetch_assets.py):
    data/upstream/cards.json              official gallery database
    data/upstream/star-realms-cards.json  community spreadsheet export

Writes:
    data/upstream/review.csv   one row per in-scope card: id, name, faction, kind,
                               cost, defense, outpost, per-set quantities, text
    data/sets.toml             trade-deck contents per set (generated; do not edit)

The engine's test suite checks data/cards.toml against review.csv, so a typo in
a hand-authored cost or defense fails `cargo test`.
"""

from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UP = ROOT / "data" / "upstream"

SETS = {"coreSet": ("core", "Core Set"), "colonyWars": ("colony_wars", "Colony Wars"), "frontiers": ("frontiers", "Frontiers")}
BASICS = {"scout", "viper", "explorer"}

# Values missing or wrong in both upstream sources.
OVERRIDES = {"blobWorld": {"defense": 7, "outpost": False}}


def norm(s: str) -> str:
    return re.sub(r"\W+", "", s.lower())


def main() -> int:
    db = json.loads((UP / "cards.json").read_text())
    sheet = json.loads((UP / "star-realms-cards.json").read_text())
    cards = {c["id"]: c for c in db["cards"]}

    sheet_by_name: dict[str, dict] = {}
    for r in sheet:
        if r["Set"] in {v[1] for v in SETS.values()}:
            sheet_by_name.setdefault(norm(r["Name"]), r)

    qty: dict[str, dict[str, int]] = {}
    for s in db["sets"]:
        if s["id"] in SETS:
            for x in s["cards"]:
                qty.setdefault(x["cardId"], {})[SETS[s["id"]][0]] = x["quantity"]

    rows = []
    problems = []
    for cid in sorted(qty):
        c = cards[cid]
        kind = c["types"][0].lower()
        defense, outpost = None, False
        if kind == "base":
            raw = sheet_by_name.get(norm(c["name"]), {}).get("Defense", "")
            m = re.match(r"\s*(\d+)\s*(Outpost)?", raw or "")
            if m:
                defense, outpost = int(m.group(1)), bool(m.group(2))
            if c["defense"] is not None and defense is not None and c["defense"] != defense:
                problems.append(f"{cid}: gallery defense {c['defense']} != spreadsheet {defense}")
            defense = defense if defense is not None else c["defense"]
        ov = OVERRIDES.get(cid, {})
        defense = ov.get("defense", defense)
        outpost = ov.get("outpost", outpost)
        if kind == "base" and defense is None:
            problems.append(f"{cid}: base without defense")
        rows.append(
            {
                "id": cid,
                "name": c["name"],
                "faction": c["factions"][0].lower().replace(" ", "_"),
                "kind": kind,
                "cost": c["cost"] if c["cost"] is not None else 0,
                "defense": defense if defense is not None else "",
                "outpost": "true" if outpost else "false",
                "core": qty[cid].get("core", 0),
                "colony_wars": qty[cid].get("colony_wars", 0),
                "frontiers": qty[cid].get("frontiers", 0),
                "text": c["text"].replace("\n---\n", " || ").replace("\n", " "),
            }
        )

    with (UP / "review.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    out = ["# Generated by tools/import_card_text.py from data/upstream/cards.json. Do not edit.", ""]
    for key, (sid, label) in SETS.items():
        out.append(f"[{sid}]")
        out.append(f'name = "{label}"')
        out.append("trade_deck = [")
        for r in sorted(rows, key=lambda r: r["id"]):
            n = r[sid]
            if n and r["id"] not in BASICS:
                out.append(f'  {{ card = "{r["id"]}", count = {n} }},')
        out.append("]")
        out.append("")
    (ROOT / "data" / "sets.toml").write_text("\n".join(out))

    for p in problems:
        print("WARN", p, file=sys.stderr)
    print(f"{len(rows)} cards -> data/upstream/review.csv, data/sets.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
